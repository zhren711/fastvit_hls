void gelu_worker(
    pack_t in_a[],
    pack_t out[],
    int    CH,
    int    H,
    int    W)
{
#pragma HLS BIND_STORAGE variable=gelu_rom type=ROM_1P impl=LUTRAM

    int total   = CH * H * W;
    int n_words = (total + 3) >> 2;

    GELU_LOOP:
    for (int w = 0; w < n_words; w++) {
#pragma HLS PIPELINE II=1
        pack_t wa = in_a[w];
        pack_t wo;
        for (int b = 0; b < 4; b++) {
#pragma HLS UNROLL
            act_t a = (act_t)wa.range(b*8+7, b*8);
            ap_uint<8> idx = (ap_uint<8>)((int)a + 128);
            wo.range(b*8+7, b*8) = gelu_rom[idx];
        }
        out[w] = wo;
    }
}
